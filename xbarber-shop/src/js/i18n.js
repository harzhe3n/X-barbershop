    const MONTHS = {
        en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'],
        ar: ['كانون الثاني', 'شباط', 'آذار', 'نيسان', 'أيار', 'حزيران', 'تموز', 'آب', 'أيلول', 'تشرين الأول', 'تشرين الثاني', 'كانون الأول'],
        ckb: ['کانوونی دووەم', 'شوبات', 'ئازار', 'نیسان', 'ئایار', 'حوزەیران', 'تەممووز', 'ئاب', 'ئەیلوول', 'تشرینی یەکەم', 'تشرینی دووەم', 'کانوونی یەکەم']
    };
    const MONTHS_SHORT_EN = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    const WEEKDAYS = {
        en: ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'],
        ar: ['الأحد', 'الاثنين', 'الثلاثاء', 'الأربعاء', 'الخميس', 'الجمعة', 'السبت'],
        ckb: ['یەکشەممە', 'دووشەممە', 'سێشەممە', 'چوارشەممە', 'پێنجشەممە', 'هەینی', 'شەممە']
    };
    const DAY_PERIOD = {
        en: ['AM', 'PM'],
        ar: ['ص', 'م'],
        ckb: ['پ.ن', 'د.ن']
    };
    const CURRENCY = { en: 'IQD', ar: 'د.ع', ckb: 'د.ع' };

    // Kurdish until someone picks another language on this device.
    const DEFAULT_LANGUAGE = 'ckb';
    const numberFormat = new Intl.NumberFormat('en-US', { maximumFractionDigits: 2 });
    let language = readStoredLanguage();

    function readStoredLanguage() {
        try {
            const stored = localStorage.getItem(STORAGE_KEY);
            return STRINGS[stored] ? stored : DEFAULT_LANGUAGE;
        } catch (error) {
            return DEFAULT_LANGUAGE;
        }
    }

    function t(key, vars) {
        const table = STRINGS[language] || STRINGS.en;
        let text;
        // A language without its own "one" form uses its normal text, not the English one.
        if (vars && Number(vars.n) === 1) text = table[`${key}_one`] ?? (key in table ? undefined : STRINGS.en[`${key}_one`]);
        if (text === undefined) text = table[key] ?? STRINGS.en[key] ?? key;
        if (vars) {
            text = text.replace(/\{(\w+)\}/g, (match, name) => (vars[name] === undefined ? match : String(vars[name])));
        }
        return text;
    }

    function getLanguage() {
        return language;
    }

    function setLanguage(code) {
        language = STRINGS[code] ? code : DEFAULT_LANGUAGE;
        try {
            localStorage.setItem(STORAGE_KEY, language);
        } catch (error) {
            // Private browsing can block storage; the choice still applies until reload.
        }
    }

    function apply() {
        const info = LANGUAGES.find(item => item.code === language) || LANGUAGES[0];
        document.documentElement.lang = info.code;
        document.documentElement.dir = info.dir;
    }

    function parseDate(value) {
        const [year, month, day] = String(value || '').split('-').map(Number);
        return { year, month: (month || 1) - 1, day: day || 1, weekday: new Date(year, (month || 1) - 1, day || 1).getDay() };
    }

    function formatDate(value, { weekday = false } = {}) {
        const date = parseDate(value);
        if (!date.year) return String(value || '');
        const showYear = date.year !== new Date().getFullYear();
        const month = MONTHS[language][date.month];
        const dayName = WEEKDAYS[language][date.weekday];
        let text;
        if (language === 'ckb') text = `${date.day}ی ${month}`;
        else text = `${date.day} ${month}`;
        if (showYear) text += ` ${date.year}`;
        if (!weekday) return text;
        return language === 'en' ? `${dayName}, ${text}` : `${dayName}، ${text}`;
    }

    function formatDateShort(value) {
        const date = parseDate(value);
        if (!date.year) return String(value || '');
        if (language === 'en') return `${date.day} ${MONTHS_SHORT_EN[date.month]}`;
        return `${date.day}/${date.month + 1}`;
    }

    function formatTime(value) {
        const match = /^(\d{1,2}):(\d{2})/.exec(String(value || ''));
        if (!match) return String(value || '');
        const hours = Number(match[1]);
        const period = DAY_PERIOD[language][hours >= 12 ? 1 : 0];
        const hour12 = hours % 12 === 0 ? 12 : hours % 12;
        return `${hour12}:${match[2]} ${period}`;
    }

    function formatNumber(value) {
        const number = Number(value || 0);
        return numberFormat.format(Number.isFinite(number) ? number : 0);
    }

    function currency() {
        return CURRENCY[language];
    }

    function formatMoney(value) {
        return `${formatNumber(value)} ${currency()}`;
    }

    function listSeparator() {
        return language === 'en' ? ', ' : '، ';
    }

    // 0 = Sunday … 6 = Saturday
    function weekdayName(index) {
        return WEEKDAYS[language][index] || '';
    }

    window.I18N = {
        languages: LANGUAGES,
        strings: STRINGS,
        t,
        getLanguage,
        setLanguage,
        apply,
        formatDate,
        formatDateShort,
        formatTime,
        formatNumber,
        formatMoney,
        currency,
        listSeparator,
        weekdayName
    };
